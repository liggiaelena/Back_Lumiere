def _build_prompt(
    region_name: str,
    condition_map: Optional[Dict[str, Any]] = None,
    lang: str = "en",
) -> str:
    """
    Build Claude prompt with SegFormer condition_map as context.

    condition_map is generated by app.segmentation.get_condition_outputs().
    Example:
        {
            "vitiligo": {"detected": False, "area_percent": 0, "zones": []},
            "melasma": {"detected": True, "area_percent": 3.2, "zones": ["left_cheek"]},
            "wine_stain": {"detected": False, "area_percent": 0, "zones": []}
        }
    """

    if condition_map:
        condition_context = json.dumps(
            condition_map,
            ensure_ascii=False,
            indent=2,
        )
    else:
        condition_context = json.dumps(
            {
                "vitiligo": {
                    "detected": False,
                    "area_percent": 0,
                    "zones": [],
                },
                "melasma": {
                    "detected": False,
                    "area_percent": 0,
                    "zones": [],
                },
                "wine_stain": {
                    "detected": False,
                    "area_percent": 0,
                    "zones": [],
                },
            },
            ensure_ascii=False,
            indent=2,
        )

    return BASE_PROMPT.format(
        region_name=region_name,
        condition_context=condition_context,
    )


async def analyze_region(
    region_name: str,
    b64_crop: str,
    condition_map: Optional[Dict[str, Any]] = None,
    lang: str = "en",
) -> dict:
    """
    Analyze one facial region crop.

    condition_map is optional for backward compatibility.
    pipeline.py will pass the SegFormer output here so Claude can use it as context.
    """

    loop = asyncio.get_event_loop()
    provider = settings.provider

    prompt = _build_prompt(
        region_name=region_name,
        condition_map=condition_map,
        lang=lang,
    )

    if provider == "anthropic":
        client = _get_anthropic_client()

        if client is None:
            print("[Vision] Anthropic client is None, returning fallback response.")
            return _fallback_response()

        try:
            result = await loop.run_in_executor(
                None,
                lambda: client.messages.create(
                    model="claude-opus-4-5",
                    max_tokens=512,
                    messages=[
                        {
                            "role": "user",
                            "content": [
                                {
                                    "type": "image",
                                    "source": {
                                        "type": "base64",
                                        "media_type": "image/jpeg",
                                        "data": b64_crop,
                                    },
                                },
                                {
                                    "type": "text",
                                    "text": prompt,
                                },
                            ],
                        }
                    ],
                ),
            )
        except Exception as exc:
            print(f"[Vision] Anthropic analysis failed. Using fallback response. Error: {exc}")
            return _fallback_response()

        raw = result.content[0].text.strip()

    else:
        return _fallback_response()

    if raw.startswith("```"):
        raw = raw.split("\n", 1)[1].rsplit("```", 1)[0].strip()

    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return _fallback_response()


